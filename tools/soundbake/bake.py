#!/usr/bin/env python3
"""Bake the pets' recorded clips (a developer tool, like tools/iconbake).

    FFMPEG=/path/to/ffmpeg python3 tools/soundbake/bake.py

Reads sounds.json beside this file, downloads each source once into
tools/soundbake/cache/ (git-ignored), cuts, filters and pitches every clip
with ffmpeg, and writes:

- assets/sounds/<clip>.wav: mono, 16-bit, 44.1 kHz, peaks at -1 dBFS. The
  app sets the loudness itself (`sound::synth`, by class), so only the peak
  is fixed here.
- licenses/sounds.md: where every clip comes from.

Only the standard library and an ffmpeg binary are needed; nothing here runs
in the app.
"""

import json
import os
import struct
import subprocess
import sys
import urllib.request
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
CACHE = os.path.join(HERE, "cache")
OUT = os.path.join(ROOT, "assets", "sounds")
RATE = 44100
PEAK = 0.891  # -1 dBFS
# A plain name for scripted downloads; never a person's address.
AGENT = "chonkgene-soundbake/1.0"


def fetch(key, url):
    os.makedirs(CACHE, exist_ok=True)
    ext = url.split("?")[0].rsplit(".", 1)[-1]
    path = os.path.join(CACHE, f"{key}.{ext}")
    if not os.path.exists(path):
        req = urllib.request.Request(url, headers={"User-Agent": AGENT})
        data = urllib.request.urlopen(req, timeout=60).read()
        with open(path + ".part", "wb") as f:
            f.write(data)
        os.replace(path + ".part", path)
    return path


def cut(ffmpeg, src, clip, dst):
    start, end = clip["start"], clip["end"]
    pitch = clip.get("pitch", 1.0)
    # 20 ms before the call and 60 ms after, so neither edge is clipped.
    a, b = max(0.0, start - 0.02), end + 0.06
    chain = [
        f"aformat=channel_layouts=mono:sample_rates={RATE}",
        f"atrim={a}:{b}",
        "asetpts=PTS-STARTPTS",
        f"highpass=f={clip.get('highpass', 110)}",
    ]
    if clip.get("denoise"):
        chain.append("afftdn=nr=14:nf=-45")
    if pitch != 1.0:
        # Higher and shorter together, like a smaller animal.
        chain += [f"asetrate={int(RATE * pitch)}", f"aresample={RATE}"]
    secs = (b - a) / pitch
    chain += ["afade=t=in:d=0.006", f"afade=t=out:st={max(0.0, secs - 0.05):.3f}:d=0.05"]
    subprocess.run(
        [ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-i", src,
         "-af", ",".join(chain), "-ac", "1", "-ar", str(RATE), "-c:a", "pcm_s16le", dst],
        check=True,
    )


def peak_to(path, peak):
    with wave.open(path) as w:
        n = w.getnframes()
        x = struct.unpack(f"<{n}h", w.readframes(n))
    top = max(1, max(abs(v) for v in x))
    g = peak * 32767 / top
    y = [max(-32767, min(32767, round(v * g))) for v in x]
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(RATE)
        w.writeframes(struct.pack(f"<{len(y)}h", *y))
    return n / RATE


def credits(spec):
    lines = [
        "# Recorded sounds",
        "",
        "The pets' calls are cut from these recordings, all dedicated to the",
        "public domain under CC0 1.0 (https://creativecommons.org/publicdomain/zero/1.0/).",
        "CC0 asks for no credit; it is given anyway. Each was checked CC0 on its",
        "own page when picked. Generated by tools/soundbake/bake.py from",
        "tools/soundbake/sounds.json.",
        "",
        "| Clip | Recording | By | Licence |",
        "|---|---|---|---|",
    ]
    for name, clip in spec["clips"].items():
        s = spec["sources"][clip["source"]]
        lines.append(f"| `{name}` | [{s['title']}]({s['page']}) | {s['author']} | {s['license']} |")
    return "\n".join(lines) + "\n"


def main():
    ffmpeg = os.environ.get("FFMPEG", "ffmpeg")
    with open(os.path.join(HERE, "sounds.json"), encoding="utf-8") as f:
        spec = json.load(f)
    os.makedirs(OUT, exist_ok=True)
    for name, clip in spec["clips"].items():
        src = fetch(clip["source"], spec["sources"][clip["source"]]["audio"])
        dst = os.path.join(OUT, f"{name}.wav")
        cut(ffmpeg, src, clip, dst)
        print(f"{name}: {peak_to(dst, PEAK):.2f} s", file=sys.stderr)
    with open(os.path.join(ROOT, "licenses", "sounds.md"), "w", encoding="utf-8") as f:
        f.write(credits(spec))


if __name__ == "__main__":
    main()
